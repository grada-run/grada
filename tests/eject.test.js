import { mockConfirm } from './helpers/clack.js';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { ejectStack, stripTerraformMetadata, stripGitignoreMetadata, isGradaBackupName } from '../src/commands/eject.js';
import { trackEvent } from '../src/core/telemetry.js';

describe('eject metadata stripping', () => {
    it('strips grada headers and tag blocks', () => {
        const content = '# grada generated infrastructure\n'
            + 'provider "aws" {\n'
            + '  region = "us-east-2"\n\n'
            + '  default_tags {\n'
            + '    tags = {\n'
            + '      ManagedBy = "grada"\n'
            + '    }\n'
            + '  }\n'
            + '}\n';
        const cleaned = stripTerraformMetadata(content);
        expect(cleaned).not.toContain('grada generated infrastructure');
        expect(cleaned).not.toContain('ManagedBy');
        expect(cleaned).toContain('provider "aws"');
        expect(cleaned).toContain('region = "us-east-2"');
    });

    it('strips tag blocks carrying the GradaProject ownership tag', () => {
        const content = 'provider "aws" {\n'
            + '  region = "us-east-2"\n\n'
            + '  default_tags {\n'
            + '    tags = {\n'
            + '      ManagedBy    = "grada"\n'
            + '      GradaProject = "myapp"\n'
            + '    }\n'
            + '  }\n'
            + '}\n';
        const cleaned = stripTerraformMetadata(content);
        expect(cleaned).not.toContain('ManagedBy');
        expect(cleaned).not.toContain('GradaProject');
        expect(cleaned).toContain('provider "aws"');
        expect(cleaned).toContain('region = "us-east-2"');
    });

    it('leaves default_tags blocks with hand-added tags in place', () => {
        const content = 'provider "aws" {\n'
            + '  default_tags {\n'
            + '    tags = {\n'
            + '      ManagedBy = "grada"\n'
            + '      CostCenter = "hand-added"\n'
            + '    }\n'
            + '  }\n'
            + '}\n';
        expect(stripTerraformMetadata(content)).toContain('CostCenter');
    });

    it('strips legacy deploy-stack headers, tag blocks, and lambda suffixes', () => {
        const content = '# deploy-stack generated infrastructure (Lambda target)\n'
            + 'provider "aws" {\n'
            + '  default_tags {\n'
            + '    tags = {\n'
            + '      ManagedBy = "deploy-stack"\n'
            + '    }\n'
            + '  }\n'
            + '}\n';
        const cleaned = stripTerraformMetadata(content);
        expect(cleaned).not.toContain('deploy-stack');
        expect(cleaned).not.toContain('Lambda target');
        expect(cleaned).toContain('provider "aws"');
    });

    it.each([
        ['grada', '# grada addon: storage:s3\n# Generated by `grada add storage:s3`. Do not edit by hand unless\n'],
        ['legacy', '# deploy-stack addon: storage:s3\n# Generated by `deploy-stack add storage:s3`. Do not edit by hand unless\n'],
    ])('strips %s addon headers but keeps billing docs', (_label, header) => {
        const content = `${header}# you know what you are doing — re-running with --force overwrites this file.\n`
            + '#\n# Billing: usage-billed.\n\nresource "aws_s3_bucket" "x" {}\n';
        const cleaned = stripTerraformMetadata(content);
        expect(cleaned).not.toContain('addon: storage:s3');
        expect(cleaned).not.toContain('Generated by');
        expect(cleaned).not.toContain('overwrites this file');
        expect(cleaned).toContain('# Billing: usage-billed.');
        expect(cleaned).toContain('resource "aws_s3_bucket" "x" {}');
    });

    it('strips both gitignore backup stanzas', () => {
        const content = 'node_modules/\n\n# grada backups\n*.bak.*\n\n# deploy-stack backups\n*.bak.*\n';
        const cleaned = stripGitignoreMetadata(content);
        expect(cleaned).not.toContain('backups');
        expect(cleaned).not.toContain('*.bak.*');
        expect(cleaned).toContain('node_modules/');
    });

    it('leaves domain markers and user content untouched', () => {
        const content = '# grada:domain-mode=route53\n# grada:zone-id=Z123\n'
            + '# A user comment about grada add workflows.\n';
        expect(stripTerraformMetadata(content)).toBe(content);
        expect(stripGitignoreMetadata('dist/\n')).toBe('dist/\n');
    });
});

describe('eject non-interactive gate', () => {
    const originalCwd = process.cwd();
    let tmpDir;
    let exitSpy;
    let consoleSpy;

    beforeEach(() => {
        vi.clearAllMocks();
        tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'eject-gate-test-'));
        process.chdir(tmpDir);
        exitSpy = vi.spyOn(process, 'exit').mockImplementation(() => { });
        consoleSpy = vi.spyOn(console, 'log').mockImplementation(() => { });
    });

    afterEach(() => {
        process.chdir(originalCwd);
        exitSpy.mockRestore();
        consoleSpy.mockRestore();
        fs.rmSync(tmpDir, { recursive: true, force: true });
    });

    it('refuses loudly when headless without approval flags instead of abandoning the eject prompt', async () => {
        const result = await ejectStack({});

        expect(result).toEqual({ ok: false, reason: 'non-interactive' });
        expect(exitSpy).toHaveBeenCalledWith(1);
        expect(trackEvent).toHaveBeenCalledWith('project_ejected', expect.objectContaining({
            success: false,
            error_code: 'EJECT_NON_INTERACTIVE',
            reason: 'non-interactive',
        }));
        expect(mockConfirm).not.toHaveBeenCalled();
        expect(fs.existsSync(path.join(tmpDir, 'STATE_BUCKET_CLEANUP.md'))).toBe(false);
        expect(fs.existsSync(path.join(tmpDir, '.grada'))).toBe(false);
    });
});

describe('eject adopted-tree gitignore negation', () => {
    const originalCwd = process.cwd();
    let tmpDir;
    let exitSpy;
    let consoleSpy;

    beforeEach(() => {
        vi.clearAllMocks();
        tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'eject-negation-test-'));
        process.chdir(tmpDir);
        fs.mkdirSync(path.join(tmpDir, 'terraform'), { recursive: true });
        fs.writeFileSync(path.join(tmpDir, 'terraform', 'main.tf'), '# fake stack\n');
        exitSpy = vi.spyOn(process, 'exit').mockImplementation(() => { });
        consoleSpy = vi.spyOn(console, 'log').mockImplementation(() => { });
    });

    afterEach(() => {
        process.chdir(originalCwd);
        exitSpy.mockRestore();
        consoleSpy.mockRestore();
        fs.rmSync(tmpDir, { recursive: true, force: true });
    });

    function writeGitignore(content) {
        fs.writeFileSync(path.join(tmpDir, '.gitignore'), content);
    }

    function readGitignore() {
        return fs.readFileSync(path.join(tmpDir, '.gitignore'), 'utf8');
    }

    it('negates the adopted var file so fresh clones keep the OIDC adoption', async () => {
        writeGitignore('node_modules/\nterraform/*.auto.tfvars\n');
        fs.writeFileSync(path.join(tmpDir, 'terraform', 'grada.auto.tfvars'), 'create_oidc_provider = false\n');
        await ejectStack({ yes: true });
        const gitignore = readGitignore();
        expect(gitignore).toContain('terraform/*.auto.tfvars');
        expect(gitignore).toContain('!terraform/grada.auto.tfvars');
        expect(gitignore.indexOf('!terraform/grada.auto.tfvars')).toBeGreaterThan(
            gitignore.indexOf('terraform/*.auto.tfvars')
        );
    });

    it('leaves the gitignore alone when nothing was adopted', async () => {
        writeGitignore('node_modules/\nterraform/*.auto.tfvars\n');
        await ejectStack({ yes: true });
        expect(readGitignore()).not.toContain('!terraform/grada.auto.tfvars');
    });

    it('never duplicates a pre-existing negation', async () => {
        writeGitignore('terraform/*.auto.tfvars\n\n# Ejected tree: keep the adopted OIDC override committed\n!terraform/grada.auto.tfvars\n');
        fs.writeFileSync(path.join(tmpDir, 'terraform', 'grada.auto.tfvars'), 'create_oidc_provider = false\n');
        await ejectStack({ yes: true });
        expect(readGitignore().match(/!terraform\/grada\.auto\.tfvars/g)).toHaveLength(1);
    });
});

