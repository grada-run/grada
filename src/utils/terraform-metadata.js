import fs from 'fs';
import path from 'path';
import color from 'picocolors';
import { confirm, cancel } from '@clack/prompts';
import { SLEEP_STATE_DIRNAME } from './sleep-state.js';
import { atomicWriteFileSync } from './atomic-write.js';
import { normalizeOptions } from './args.js';
import { failCommand, shouldAutoApprove } from './command.js';
import { resolveHeadless } from './resolvers.js';
import { trackEvent } from '../core/telemetry.js';

// Shared home for grada provenance metadata: stripping managed markers
// from Terraform (eject) and detecting ejected projects (add/init).
// `src/commands/eject.js` re-exports the strip helpers so existing
// importers keep working.

// Matches the `# <brand> generated infrastructure...` header line in
// either brand variant (Lambda targets append a suffix in parentheses).
const GENERATED_HEADER_REGEX = /# (?:grada|deploy-stack) generated infrastructure[^\n]*\n?/g;

// Matches the one-line `# <brand> addon: ...` header in either variant.
const ADDON_HEADER_REGEX = /^# (?:grada|deploy-stack) addon:[^\n]*\n?/gm;

// Matches the `# Generated by \`<brand> add ...` sentence through its
// `... overwrites this file.` tail (it wraps across lines), in either
// brand variant. Billing docs below the header are left untouched.
const GENERATED_BY_REGEX = /^# Generated by `?(?:grada|deploy-stack) add\b[^\n]*\n(?:^#[^\n]*\n)*?^#[^\n]*overwrites this file\.[^\n]*\n?/gm;

// Matches a `default_tags` block pinning `ManagedBy` to either brand,
// with or without the generated `GradaProject` ownership tag. Blocks
// carrying any other hand-added tags are left in place (safe direction:
// leftover tags, never stripped user data).
const MANAGED_BY_TAGS_REGEX = /[ \t]*default_tags\s*\{\s*tags\s*=\s*\{\s*ManagedBy\s*=\s*"(?:grada|deploy-stack)"(?:\s*GradaProject\s*=\s*"[^"]*")?\s*\}\s*\}\n?/g;

// Matches the `.bak` gitignore stanza in either brand variant.
const BACKUPS_GITIGNORE_REGEX = /\n# (?:grada|deploy-stack) backups\n\*\.bak\.\*\n/g;

// Strips tool metadata from Terraform source: the generated header,
// addon headers, and ManagedBy tag blocks. Pure and unit-tested.
export function stripTerraformMetadata(content) {
    return String(content ?? '')
        .replace(GENERATED_HEADER_REGEX, '')
        .replace(ADDON_HEADER_REGEX, '')
        .replace(GENERATED_BY_REGEX, '')
        .replace(MANAGED_BY_TAGS_REGEX, '');
}

// Strips the `.bak` stanza from gitignore content. Pure and unit-tested.
export function stripGitignoreMetadata(content) {
    return String(content ?? '').replace(BACKUPS_GITIGNORE_REGEX, '\n');
}

export const EJECTED_MARKER_FILENAME = 'ejected.json';

export function ejectedMarkerPath(cwd = process.cwd()) {
    return path.join(cwd, SLEEP_STATE_DIRNAME, EJECTED_MARKER_FILENAME);
}

// Records that the project was ejected. Lives in the gitignored local
// state dir so the ejected tree itself stays 100% vanilla.
export function writeEjectedMarker(cwd = process.cwd()) {
    const markerPath = ejectedMarkerPath(cwd);
    fs.mkdirSync(path.dirname(markerPath), { recursive: true });
    const marker = { ejectedAt: new Date().toISOString() };
    atomicWriteFileSync(markerPath, `${JSON.stringify(marker, null, 2)}\n`, 'utf8');
    return marker;
}

// Returns the ejected marker, or null when the project is still
// grada-managed (or predates markers).
export function readEjectedMarker(cwd = process.cwd()) {
    try {
        const raw = fs.readFileSync(ejectedMarkerPath(cwd), 'utf8');
        const parsed = JSON.parse(raw);
        return parsed && typeof parsed === 'object' ? parsed : null;
    } catch {
        return null;
    }
}

export const EJECTED_SENTINEL_FILENAME = '.grada-ejected';

export function ejectedSentinelPath(cwd = process.cwd()) {
    return path.join(cwd, EJECTED_SENTINEL_FILENAME);
}

// The committed eject record: unlike the gitignored local marker, the
// sentinel travels with clones, so a fresh checkout never silently
// re-manages an ejected tree. Never gitignored by grada itself.
export function writeEjectedSentinel(cwd = process.cwd()) {
    const sentinel = {
        ejectedAt: new Date().toISOString(),
        note: 'This project was ejected from grada. The terraform/ tree is user-owned vanilla Terraform; grada commands refuse to manage it without --force.',
    };
    atomicWriteFileSync(ejectedSentinelPath(cwd), `${JSON.stringify(sentinel, null, 2)}\n`, 'utf8');
    return sentinel;
}

// Returns the committed sentinel, or null when absent/unparseable.
export function readEjectedSentinel(cwd = process.cwd()) {
    try {
        const raw = fs.readFileSync(ejectedSentinelPath(cwd), 'utf8');
        const parsed = JSON.parse(raw);
        return parsed && typeof parsed === 'object' ? parsed : null;
    } catch {
        return null;
    }
}

// Shared eject consult for init's gate and requireManagedTree:
// `{ marker, sentinel }` booleans, plus `which` for telemetry
// ('marker' | 'sentinel' | 'both' | null when managed).
export function detectEjectedState(cwd = process.cwd()) {
    const marker = readEjectedMarker(cwd) !== null;
    const sentinel = readEjectedSentinel(cwd) !== null;
    return {
        marker,
        sentinel,
        which: marker && sentinel ? 'both' : marker ? 'marker' : sentinel ? 'sentinel' : null,
    };
}

// Parses the state-bucket backend block shared by destroy's cleanup and
// eject's handoff doc. Pure over file text: `{ bucket, region }`, each
// null when the backend block names nothing.
export function parseStateBucketBackend(content) {
    const text = String(content ?? '');
    const bucketMatch = text.match(/bucket\s*=\s*"([^"]+)"/);
    const regionMatch = text.match(/region\s*=\s*"([^"]+)"/);
    return {
        bucket: bucketMatch ? bucketMatch[1] : null,
        region: regionMatch ? regionMatch[1] : null,
    };
}

// Central managed-tree gate: mutating commands refuse on ejected trees
// unless --force (headless fails, interactive confirms once);
// read-only callers pass `mode: 'warn'` to warn and proceed. Returns
// `{ proceed, ejected?, result? }`: `result` is the command's return
// value when `proceed` is false.
export async function requireManagedTree({
    cwd = process.cwd(),
    command,
    options = {},
    event = null,
    projectName = null,
    mode = 'refuse',
    noExit = false,
} = {}) {
    const opts = normalizeOptions(options);
    const { which } = detectEjectedState(cwd);
    if (!which) return { proceed: true };
    const project = projectName ?? path.basename(path.resolve(cwd));

    if (mode === 'warn') {
        console.log(color.yellow(`⚠ This project was ejected from grada (${which}) — ${command} shows live state, but grada no longer manages this tree.`));
        return { proceed: true, ejected: which };
    }
    if (opts.force === true || opts.force === 'true') return { proceed: true, ejected: which };

    if (shouldAutoApprove(opts) || resolveHeadless(opts)) {
        trackEvent('managed_tree_refused', { projectName: project, command });
        return {
            proceed: false,
            result: await failCommand({
                message: `\n✖ This project was ejected from grada — ${command} no longer manages it.`,
                hint: '  Re-run with --force to proceed anyway, or manage the Terraform by hand.\n',
                event,
                telemetry: { projectName: project },
                errorCode: 'EJECTED_PROJECT',
                reason: 'ejected-project',
                noExit,
            }),
        };
    }
    console.log(color.yellow(`⚠ This project was ejected from grada (${which}) — ${command} would act on a tree grada no longer manages.`));
    const confirmed = await confirm({
        message: `This tree is ejected. Run ${command} anyway?`,
        initialValue: false,
    });
    if (confirmed === true) return { proceed: true, ejected: which };
    trackEvent('managed_tree_refused', { projectName: project, command });
    cancel(`${command[0].toUpperCase()}${command.slice(1)} cancelled. The ejected tree was left untouched.`);
    if (!noExit) process.exit(0);
    return { proceed: false, result: { ok: false, reason: 'cancelled', ...(noExit ? { exitCode: 0 } : {}) } };
}
